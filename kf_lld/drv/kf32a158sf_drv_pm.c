/**
 * @brief 设置FVR2
 *
 * @param FvrVoltage FVR电压
 */
void Pm_LL_SetFvr2(Pm_FvrVoltage_t FvrVoltage, bool EnableState)
{
    Bkp_LL_PmRegisterHandleStart();

    if (EnableState)
    {
        if (!Pm_LL_GetFvrCaplessEnabledState())
        {
            Pm_LL_SelectFvr2Voltage(FvrVoltage);
            Pm_LL_SetFvrCaplessMode(true);
            Pm_LL_SetFvrCaplessEnabled(true);
        }
        else
        { /*Empty*/
        }
    }
    else
    {
        Pm_LL_SetFvrCaplessEnabled(false);
    }

    Bkp_LL_PmRegisterHandleEnd();
}

